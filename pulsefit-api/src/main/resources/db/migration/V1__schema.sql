-- Initial schema, docs/backend-spec.md §5.
-- Runs as role pulsefit_api, which owns everything created here.
-- Flyway is configured with schemas=app, so the schema already exists when
-- this runs; the statement is kept so the file matches the spec on its own.
create schema if not exists app;

create table app.profiles (
  id          uuid primary key,               -- = auth.users.id
  created_at  timestamptz not null default now()
);

create table app.activities (
  id                  uuid primary key,       -- generated by the client
  user_id             uuid not null references app.profiles(id) on delete cascade,
  type                text not null check (type in ('WALKING','RUNNING','INLINE_SKATING','CYCLING')),
  title               text not null check (char_length(title) between 1 and 80),
  started_at          timestamptz not null,
  ended_at            timestamptz not null check (ended_at >= started_at),
  zone_id             text not null,
  active_duration_ms  bigint not null check (active_duration_ms >= 0),
  elapsed_duration_ms bigint not null check (elapsed_duration_ms >= active_duration_ms),
  distance_m          double precision not null check (distance_m >= 0),
  avg_speed_mps       double precision not null check (avg_speed_mps >= 0),
  max_speed_mps       double precision not null check (max_speed_mps >= 0),
  elevation_gain_m    double precision,
  time_slow_ms        bigint not null default 0,
  time_average_ms     bigint not null default 0,
  time_high_ms        bigint not null default 0,
  source              text not null check (source in ('PHONE','WATCH')),
  preview_polylines   text[] not null,                    -- simplified track, one encoded polyline per segment
  version             bigint not null default 1,          -- +1 on every change
  created_at          timestamptz not null default now(),
  updated_at          timestamptz not null default now(), -- server clock, set on every change
  deleted_at          timestamptz                          -- tombstone
);
create index activities_sync_idx on app.activities (user_id, updated_at, id);
create index activities_list_idx on app.activities (user_id, started_at desc) where deleted_at is null;

create table app.track_points (
  activity_id uuid not null references app.activities(id) on delete cascade,
  seq         integer not null,
  segment     integer not null,
  lat         double precision not null check (lat between -90 and 90),
  lng         double precision not null check (lng between -180 and 180),
  altitude_m  double precision,
  speed_mps   real,
  accuracy_m  real not null,
  recorded_at timestamptz not null,
  primary key (activity_id, seq)
);

-- No policies: anon and authenticated can read nothing even if the schema were
-- exposed through PostgREST. The owner (pulsefit_api) is not subject to RLS.
alter table app.profiles     enable row level security;
alter table app.activities   enable row level security;
alter table app.track_points enable row level security;
